#!/usr/bin/env python3
"""Generate the website tutorial from manual section 6; no app build/network.

Python-Markdown is a build-time dependency only (tested with 3.5.2).
Default is read-only --check. --write explicitly updates the generated page.
"""
import argparse
import hashlib
import html
import posixpath
import re
from pathlib import Path
from urllib.parse import urlsplit

import markdown

ROOT = Path(__file__).resolve().parents[1]
LANGS = {"en": ("en", "Your first piece", "Presentation", "Full manual"),
         "pt": ("pt-BR", "Sua primeira peça", "Apresentação", "Manual completo"),
         "fr": ("fr", "Votre première pièce", "Présentation", "Manuel complet"),
         "es": ("es", "Tu primera pieza", "Presentación", "Manual completo")}
PAGES = {"en": "en.html", "pt": "index.html", "fr": "fr.html", "es": "es.html"}
FAMILY = "https://rasgoinstruments.arquiviagem.net/"
STRIPS = {"pt": "RASGO — família de instrumentos e pesquisa sonora",
          "en": "RASGO — instrument family and sound research",
          "fr": "RASGO — famille d’instruments et recherche sonore",
          "es": "RASGO — familia de instrumentos e investigación sonora"}


def tutorial_section(source):
    parts = re.split(r"^## 6\. [^\n]+\n", source, maxsplit=1, flags=re.M)
    if len(parts) != 2:
        raise ValueError("manual must contain a unique section 6")
    body = re.split(r"^## [^\n]+\n", parts[1], maxsplit=1, flags=re.M)[0]
    if len(body.encode()) > 64 * 1024:
        raise ValueError("tutorial exceeds the bounded page budget")
    return body


def render_body(source, lang):
    body = markdown.markdown(tutorial_section(source), extensions=["tables", "fenced_code", "toc"])
    body = body.replace("<h3", "<h2").replace("</h3>", "</h2>")
    body = re.sub(r'id="([^"]+)"', lambda m: f'id="{lang}--{m[1]}"', body)

    def link(match):
        raw = html.unescape(match[1])
        url = urlsplit(raw)
        if url.scheme or url.netloc or not url.path:
            return match[0]
        target = posixpath.normpath(posixpath.join("docs", lang, url.path))
        relative = posixpath.relpath(target, "website")
        if url.fragment:
            relative += "#" + url.fragment
        return 'href="' + html.escape(relative, quote=True) + '"'

    return re.sub(r'href="([^"]+)"', link, body)


def generate(root=ROOT):
    sources, articles = [], []
    for code, (lang, title, presentation, manual) in LANGS.items():
        path = root / "docs" / code / "manual.md"
        if path.is_symlink() or path.parent.is_symlink() or path.stat().st_size > 128 * 1024:
            raise ValueError("manual outside the safe input budget")
        raw = path.read_bytes()
        sources.append(f"docs/{code}/manual.md SHA256 {hashlib.sha256(raw).hexdigest()}")
        body = render_body(raw.decode("utf-8"), code)
        articles.append(f'<article id="{code}" lang="{lang}" data-tutorial-language="{code}" data-reviewed="2026-10-12">'
                        f'<h1>{title}</h1>\n{body}\n<p><a href="../docs/{code}/manual.md">{manual}</a>'
                        f' · <a href="{PAGES[code]}">{presentation}</a></p></article>')
    nav = '\n'.join(f'<a href="#{code}" data-language="{code}" lang="{LANGS[code][0]}">{name}</a>'
                    for code, name in [("en", "English"), ("pt", "Português"), ("fr", "Français"), ("es", "Español")])
    notice = '\n'.join(sources)
    return ('<!doctype html>\n<!-- GENERATED by tools/build_studio_tutorial.py; edit manuals, not this page.\n'
            + notice + '\n-->\n<html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            '<title>Rasgo Synth Studio — Tutorials / Tutoriais</title>'
            '<meta name="description" content="Learn Studio step by step: controls, listening exercises, module choices and your first album. EN/PT/FR/ES.">'
            '<link rel="stylesheet" href="assets/site.css?v=6">'
            '<link rel="stylesheet" href="assets/studio.css?v=2">'
            '<script src="assets/quickstart.js" defer></script></head><body class="studio-public">'
            '<div class="rasgo-strip" aria-label="RASGO">'
            + ''.join(f'<a href="{FAMILY}{"" if code == "pt" else PAGES[code]}" lang="{LANGS[code][0]}" data-family-language="{code}">{STRIPS[code]}</a>' for code in LANGS)
            + '</div><a class="studio-skip" href="#tutorial-content">Skip / Pular / Aller au / Ir al contenido</a>'
            '<header class="studio-header topbar"><a class="studio-mark mark" href="index.html">'
            '<img class="mark-logo" src="assets/rasgo_logo.svg" width="136" height="28" alt="RASGO">'
            'RASGO<span>SYNTH</span> · STUDIO</a>'
            f'<nav aria-label="Tutorial language">{nav}</nav></header>'
            '<main id="tutorial-content" class="quickstart"><header>'
            '<p>RASGO SYNTH STUDIO · 0.1.0 EXPERIMENTAL · 2026-10-12</p>'
            '</header>'
            + '\n'.join(articles) + '</main></body></html>\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    generated = generate()
    target = ROOT / "website/quickstart.html"
    if target.is_symlink():
        raise ValueError("refusing a symlink output")
    if args.write:
        target.write_text(generated, encoding="utf-8")
        print("Generated website/quickstart.html from four canonical manuals")
    elif target.read_text(encoding="utf-8") != generated:
        parser.exit(1, "Tutorial is stale: run python3 -B tools/build_studio_tutorial.py --write\n")
    else:
        print("PASS: four-language tutorial matches the canonical manuals")


if __name__ == "__main__":
    main()
